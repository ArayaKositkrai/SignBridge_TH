// ต้องตรงกับ FACE_KEYPOINTS ใน ml/src/features.py
export const FACE_KEYPOINTS = [
  70, 63, 105, 66, 107, // 0-4   คิ้วข้างหนึ่ง
  300, 293, 334, 296, 336, // 5-9   คิ้วอีกข้าง
  33, 160, 158, 133, 153, 144, // 10-15 ตา
  362, 385, 387, 263, 373, 380, // 16-21 ตาอีกข้าง
  61, 40, 37, 0, 267, 270, 291, 321, 314, 17, 84, 91, // 22-33 ปากด้านนอก
  78, 81, 13, 311, 308, 402, 14, 178, // 34-41 ปากด้านใน
  1, 152, 10, 234, 454, // 42-46 ปลายจมูก คาง หน้าผาก แก้ม แก้ม
];

// เส้นที่ใช้วาดจุดสำคัญ (ลำดับในรายการข้างบน): คิ้ว ตา ปากนอก ปากใน
const range = (a: number, b: number) => Array.from({ length: b - a + 1 }, (_, i) => a + i);
export const FACE_KEYPOINT_LINES: number[][] = [
  range(0, 4),
  range(5, 9),
  [...range(10, 15), 10],
  [...range(16, 21), 16],
  [...range(22, 33), 22],
  [...range(34, 41), 34],
];

// เลือกเฉพาะจุดสำคัญจากใบหน้าเต็ม (ไม่เห็นหน้า = รายการว่าง)
export function pickFaceKeypoints<T>(face: T[]): T[] {
  return face.length >= 468 ? FACE_KEYPOINTS.map((i) => face[i]) : [];
}
